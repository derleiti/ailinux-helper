'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const {validateLinuxArtifacts} = require('../linux-package-validation');

const linux = new Map([['linux', new Map([['deb', {}]])]]);
const win = new Map([['win', new Map([['nsis', {}]])]]);

test('validates actual current DEB paths, independent of configured output directory', () => {
  const seen = [];
  const fresh = '/tmp/dist-candidate/helper.deb';
  const result = {
    platformToTargets: linux,
    artifactPaths: [fresh, fresh, '/tmp/dist-candidate/helper.AppImage'],
    outDir: '/tmp/dist-candidate',
  };
  assert.deepEqual(validateLinuxArtifacts(result, file => seen.push(file)), []);
  assert.deepEqual(seen, [fresh]);
});

test('fails if a requested DEB was not produced, even if old dist exists', () => {
  assert.throws(
    () => validateLinuxArtifacts({platformToTargets: linux, artifactPaths: ['dist/helper.AppImage']}, () => {}),
    /No Linux DEB generated by the current build/
  );
});

test('non-DEB targets do not invoke the DEB validator', () => {
  assert.deepEqual(validateLinuxArtifacts(
    {platformToTargets: win, artifactPaths: ['dist/helper.exe']},
    () => assert.fail('unexpected DEB validation')
  ), []);
});
