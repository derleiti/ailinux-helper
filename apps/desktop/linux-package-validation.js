'use strict';

const path = require('node:path');
const {execFileSync} = require('node:child_process');
const {version} = require('./package.json');

function verifyDeb(file) {
  const validator = path.resolve(__dirname, '../../scripts/verify-linux-deb.py');
  execFileSync('python3', [validator, file, '--version', version], {stdio: 'inherit'});
}

function validateLinuxArtifacts(result, validate = verifyDeb) {
  const expectsDeb = [...result.platformToTargets.values()].some(targets => targets.has('deb'));
  const packages = [...new Set(result.artifactPaths.filter(file => file.endsWith('.deb')))];
  if (expectsDeb && packages.length === 0) {
    throw new Error('No Linux DEB generated by the current build');
  }
  for (const file of packages) validate(file);
  return [];
}

module.exports = async function afterAllArtifactBuild(result) {
  return validateLinuxArtifacts(result);
};
module.exports.validateLinuxArtifacts = validateLinuxArtifacts;
